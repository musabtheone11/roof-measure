import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const RM = createRequire(import.meta.url)('../roofmodel.js');
const evidence = (kinds) => Object.fromEntries(kinds.map(k => [k, {status:'measured',source:'Illustrative calibrated fixture',date:'2026-11-20',basis:'known synthetic coordinates'}]));
const job = {facets:[{id:'F1',path:[{lat:0,lng:0},{lat:0,lng:1},{lat:1,lng:1}],measurementEvidence:evidence(['geometry','pitch','area'])}],edges:[{id:'E1',type:'eave',path:[{lat:0,lng:0},{lat:0,lng:1}],measurementEvidence:evidence(['geometry','type','length'])}]};
for (const item of [...job.facets,...job.edges]) for (const [kind,e] of Object.entries(item.measurementEvidence)) e.revision=RM.evidenceRevision(item,kind);
const ctx = {selectionVerified:true,scaleVerified:true};
assert.equal(RM.auditEvidence(job,ctx).ok,true);
const legacy = {facets:[{id:'F1',status:'measured',path:job.facets[0].path}]};
assert.equal(RM.auditEvidence(legacy,ctx).ok,false,'legacy measured flag cannot establish provenance');
const wrong = structuredClone(job); wrong.facets[0].path = [{lat:0,lng:0},{lat:0,lng:2},{lat:.5,lng:1}];
assert.notEqual(RM.modelRevision(wrong),RM.modelRevision(job),'equal area wrong outline has distinct revision');
assert(RM.auditEvidence(wrong,{...ctx,reportRevision:RM.modelRevision(job)}).issues.some(x=>x.code==='stale-report'));
const edited = structuredClone(job); edited.facets[0].pitch=7;
assert(RM.auditEvidence(edited,{...ctx,reportRevision:RM.modelRevision(job)}).issues.some(x=>x.code==='stale-report'));
const tree = structuredClone(job); tree.edges[0].measurementEvidence.type.basis='canopy boundary';
assert(RM.auditEvidence(tree,ctx).issues.some(x=>x.code==='non-roof-boundary'));
const unknownPitch = structuredClone(job); delete unknownPitch.facets[0].measurementEvidence.pitch;
assert(RM.auditEvidence(unknownPitch,ctx).issues.some(x=>x.quantity==='pitch'));
assert.equal(RM.reportStatus({facets:1,reconcileOk:true,evidenceAudit:RM.auditEvidence(unknownPitch,ctx)}).status,'REVIEW REQUIRED');
assert.equal(RM.reportStatus({facets:1,reconcileOk:true,unclassifiedFt:4}).status,'REVIEW REQUIRED');
assert.equal(RM.modelRevision({...job,camera:{angle:1}}),RM.modelRevision({...job,camera:{angle:2}}),'orbit camera does not change canonical model');
for (const [list,key,value] of [['facets','path',wrong.facets[0].path],['facets','pitch',7],['edges','type','rake']]) {
  const changed=structuredClone(job); changed[list][0][key]=value;
  assert(RM.auditEvidence(changed,ctx).issues.some(x=>x.code==='stale-evidence'),key+' edits invalidate old evidence');
}
const unsupported = structuredClone(job); unsupported.facets[0].pitchUnknown = true;
assert(RM.auditEvidence(unsupported,ctx).issues.some(x=>x.code==='unsupported-quantity'), 'provenance cannot override explicit unknown pitch');
const inherited = structuredClone(job); inherited.edges[0].type = 'rake'; inherited.defaultPitch = 6;
const before = RM.evidenceRevision(inherited.edges[0], 'length', inherited);
inherited.facets[0].pitch = 8;
assert.notEqual(before, RM.evidenceRevision(inherited.edges[0], 'length', inherited), 'adjoining pitch edits invalidate inherited length evidence');
const next = RM.evidenceRevision(inherited.edges[0], 'length', inherited); inherited.defaultPitch = 9;
assert.notEqual(next, RM.evidenceRevision(inherited.edges[0], 'length', inherited), 'default pitch edits invalidate inherited length evidence');
const inferred = structuredClone(job); inferred.facets[0].measurementEvidence.geometry.status = 'inferred';
const inferredAudit = RM.auditEvidence(inferred,ctx);
assert(inferredAudit.issues.some(x=>x.code==='inferred-quantity'));
assert(!inferredAudit.issues.some(x=>x.code==='quantity-evidence'));
assert.equal(RM.reportStatus({facets:1,evidenceAudit:inferredAudit}).status,'REVIEW REQUIRED');
assert.equal(RM.reportStatus({facets:1,evidenceAudit:inferredAudit}).reasons.find(x=>x.code==='inferred-quantity').id, 'F1', 'status retains stable evidence IDs for schedule cross-references');
console.log('Evidence gate: 20 checks passed');
