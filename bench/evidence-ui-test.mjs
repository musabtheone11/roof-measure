import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
const RM = createRequire(import.meta.url)('../roofmodel.js');
const source = fs.readFileSync(new URL('../review.js', import.meta.url), 'utf8');
const helpers = source.slice(source.indexOf('function reviewScopeRevision('), source.indexOf('function renderQuantityEvidence('));
const state = { address: 'synthetic', location: {lat:1,lng:1}, facets: [{modelId:'F-stable',path:[{lat:1,lng:1},{lat:1,lng:2},{lat:2,lng:2}],pitch:6}], edges:[{modelId:'E-stable',path:[{lat:1,lng:1},{lat:1,lng:2}],type:'eave'}], trace:null };
let recomputations=0;
const ctx = vm.createContext({RM,state,serialize:()=>JSON.parse(JSON.stringify(state)),reviewLog:()=>{},recompute:()=>{recomputations++;}});
vm.runInContext(helpers,ctx);
const record={source:'Synthetic calibrated fixture',date:'2026-11-20',basis:'Known geometry at 10 cm resolution',status:'measured'};
ctx.reviewRecordQuantity('F-stable','geometry',record);
assert.equal(state.facets[0].measurementEvidence.geometry.status,'measured');
assert.equal(state.facets[0].measurementEvidence.pitch,undefined,'one quantity must not certify another');
assert.equal(state.facets[0].measurementEvidence.geometry.revision,RM.evidenceRevision(state.facets[0],'geometry',state));
assert.throws(()=>ctx.reviewRecordQuantity('E-stable','pitch',record),/applicable quantity/);
assert.throws(()=>ctx.reviewRecordQuantity('F-stable','pitch',{...record,date:'2026-02-30'}),/valid YYYY/);
assert.equal(ctx.reviewEvidenceContext().selectionVerified,false,'unrecorded selection stays unknown');
ctx.reviewRecordScope({...record,selectionVerified:true,scaleVerified:true});
assert.equal(ctx.reviewEvidenceContext().selectionVerified,true);
assert.equal(ctx.reviewEvidenceContext().scaleVerified,true);
ctx.reviewRecordQuantity('F-stable','pitch',record);
assert.equal(ctx.reviewEvidenceContext().selectionVerified,true,'adding provenance does not alter scope');
state.facets[0].path[0].lng += .01;
assert.equal(ctx.reviewEvidenceContext().selectionVerified,false,'changed outline invalidates selection check');
assert.equal(ctx.reviewEvidenceContext().scaleVerified,false,'changed outline invalidates scale check');
assert.equal(recomputations,3);
console.log('evidence UI helpers: individual quantities, metadata validation and revision-bound scope pass');
